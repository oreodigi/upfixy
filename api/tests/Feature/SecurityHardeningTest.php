/**
 * Task 5 hardening: tamper-evident audit (ACC-007), MFA lockout (ACC-002), password reset,
 * workspace soft close (NFR-14), and failure scenarios for queues/connectors/payments.
 */
class SecurityHardeningTest extends TestCase
{
    private array $f;

    protected function setUp(): void
    {
        parent::setUp();
        Mail::fake();
        // The per-IP rate limiters (6/min MFA, 5/min reset) are tested elsewhere; here we test the account lockout itself.
        $this->withoutMiddleware(\Illuminate\Routing\Middleware\ThrottleRequests::class);
        $f = [];
        foreach (['olive', 'tina', 'bob'] as $n) $f[$n] = $this->makeUser($n);
        $f['ws'] = $this->makeWorkspace('Agency');
        $this->addMember($f['ws'], $f['olive'], 'owner');
        $this->addMember($f['ws'], $f['tina'], 'technician');
        $f['secret'] = $this->enableMfa($f['olive']);
        $this->enableMfa($f['tina']);
        $this->f = $f;
    }

    private function worker()
    {
        return DB::connection('pgsql_worker');
    }

    // ------------------------------------------------------------ audit chain
    public function test_audit_trail_is_hash_chained_and_tampering_is_detected(): void
    {
        foreach (['First', 'Second', 'Third', 'Fourth'] as $n) $this->api($this->f['olive'], $this->f['ws'], 'POST', 'clients', ['name' => "Client {$n}"])->assertCreated();
        $this->assertNull($this->worker()->selectOne('SELECT * FROM audit_verify(0)')->broken_id);
        $rows = $this->owner()->select('SELECT id, prev_hash, row_hash FROM audit_events ORDER BY id');
        $this->assertGreaterThanOrEqual(4, count($rows));
        for ($i = 1; $i < count($rows); $i++) $this->assertSame($rows[$i - 1]->row_hash, $rows[$i]->prev_hash);
        $anchor = $this->worker()->selectOne('SELECT * FROM audit_anchor()');

        // A database owner edits one row quietly.
        $victim = $rows[1]->id;
        $this->owner()->unprepared('ALTER TABLE audit_events DISABLE TRIGGER USER');
        $this->owner()->update("UPDATE audit_events SET detail = '{\"name\":\"edited\"}' WHERE id = ?", [$victim]);
        $r = $this->worker()->selectOne('SELECT * FROM audit_verify(0)');
        $this->assertSame((int) $victim, (int) $r->broken_id);
        $this->assertStringContainsString('changed', $r->reason);

        // ...then rewrites every hash after it to hide the edit: the external anchor still catches it.
        $prev = $this->owner()->selectOne('SELECT row_hash FROM audit_events WHERE id < ? ORDER BY id DESC LIMIT 1', [$victim])->row_hash;
        foreach ($this->owner()->select('SELECT id FROM audit_events WHERE id >= ? ORDER BY id', [$victim]) as $x) {
            $h = $this->owner()->selectOne('SELECT audit_row_hash(?, a) AS h FROM audit_events a WHERE id = ?', [$prev, $x->id])->h;
            $this->owner()->update('UPDATE audit_events SET prev_hash = ?, row_hash = ? WHERE id = ?', [$prev, $h, $x->id]);
            $prev = $h;
        }
        $this->assertNull($this->worker()->selectOne('SELECT * FROM audit_verify(0)')->broken_id, 'a full rewrite passes the internal check…');
        $this->assertNotSame($anchor->last_hash, $this->owner()->selectOne('SELECT row_hash FROM audit_events WHERE id = ?', [$anchor->last_id])->row_hash,
            '…but no longer matches the anchor kept outside the database');

        // Deleting a row breaks the link of the next one.
        $this->owner()->delete('DELETE FROM audit_events WHERE id = ?', [$rows[2]->id]);
        $this->assertSame((int) $rows[3]->id, (int) $this->worker()->selectOne('SELECT * FROM audit_verify(0)')->broken_id);
        $this->owner()->unprepared('ALTER TABLE audit_events ENABLE TRIGGER USER');
    }

    public function test_the_app_cannot_choose_audit_ids_hashes_times_or_trace_ids(): void
    {
        \App\Support\TenantContext::apply($this->f['olive']->id, $this->f['ws']);
        try {
            foreach (["INSERT INTO audit_events(action, outcome, row_hash) VALUES ('x', 'allowed', 'forged')",
                         "INSERT INTO audit_events(id, action, outcome) VALUES (1, 'x', 'allowed')",
                         "INSERT INTO audit_events(action, outcome, created_at) VALUES ('x', 'allowed', '2000-01-01')"] as $sql) {
                try {
                    DB::connection('pgsql')->transaction(fn () => DB::statement($sql));
                    $this->fail("app ran: {$sql}");
                } catch (QueryException $e) {
                    $this->assertSame('42501', $e->getCode(), $sql);
                }
            }
        } finally {
            \App\Support\TenantContext::clear();
        }
        // trace_id is generated by the server; a client header is kept only as a hint.
        $this->call('POST', '/api/v1/clients', ['name' => 'Traced'], [], [], [
            'HTTP_AUTHORIZATION' => 'Bearer ' . $this->tokenFor($this->f['olive']), 'HTTP_X_WORKSPACE_ID' => $this->f['ws'],
            'HTTP_ACCEPT' => 'application/json', 'HTTP_X_REQUEST_ID' => 'client-chosen-id'])->assertCreated();
        $row = $this->owner()->selectOne("SELECT trace_id, detail FROM audit_events WHERE action = 'client.created' ORDER BY id DESC LIMIT 1");
        $this->assertMatchesRegularExpression('/^[0-9a-f-]{36}$/', $row->trace_id);
        $this->assertSame('client-chosen-id', json_decode($row->detail, true)['client_request_id']);
    }

    // ------------------------------------------------------------ MFA lockout
    public function test_five_wrong_codes_lock_code_entry_everywhere_and_notify_the_user(): void
    {
        for ($i = 0; $i < 5; $i++) {
            $this->api($this->f['olive'], null, 'POST', 'mfa/verify', ['code' => '000000'])->assertStatus(422);
        }
        $u = $this->owner()->selectOne('SELECT mfa_locked_until, mfa_lockouts FROM users WHERE id = ?', [$this->f['olive']->id]);
        $this->assertNotNull($u->mfa_locked_until);
        $this->assertEqualsWithDelta(15 * 60, strtotime($u->mfa_locked_until) - time(), 30);
        Mail::assertSent(SecurityNoticeMail::class, fn ($m) => $m->kind === 'mfa_locked' && $m->hasTo('olive@test.local'));
        // Even the right code is refused while locked, on any session.
        $this->api($this->f['olive'], null, 'POST', 'mfa/verify', ['code' => $this->totp($this->f['secret'])])
            ->assertStatus(429)->assertJsonPath('code', 'mfa_locked');
        $this->assertNotEmpty($this->auditRows('mfa.locked_out'));

        // After the lock expires a correct code works and the counters reset.
        $this->owner()->update("UPDATE users SET mfa_locked_until = now() - interval '1 second' WHERE id = ?", [$this->f['olive']->id]);
        $this->api($this->f['olive'], null, 'POST', 'mfa/verify', ['code' => $this->totp($this->f['secret'], 1)])->assertOk();
        $u = $this->owner()->selectOne('SELECT mfa_failures, mfa_lockouts, mfa_locked_until FROM users WHERE id = ?', [$this->f['olive']->id]);
        $this->assertSame([0, 0, null], [(int) $u->mfa_failures, (int) $u->mfa_lockouts, $u->mfa_locked_until]);
    }

    public function test_repeat_lockouts_get_longer_and_the_sign_in_step_is_covered_too(): void
    {
        $this->owner()->update('UPDATE users SET mfa_lockouts = 2 WHERE id = ?', [$this->f['olive']->id]);
        $login = fn () => $this->postJson('/api/v1/auth/login', ['email' => 'olive@test.local', 'password' => 'correct-horse-battery'])->json('challenge_token');
        $this->owner()->update('UPDATE users SET password_hash = ? WHERE id = ?', [\Illuminate\Support\Facades\Hash::make('correct-horse-battery'), $this->f['olive']->id]);
        $challenge = $login();
        $this->assertNotEmpty($challenge);
        for ($i = 0; $i < 5; $i++) {
            $this->postJson('/api/v1/auth/mfa/login', ['code' => '111111'], ['Authorization' => "Bearer {$challenge}"])->assertStatus(422);
        }
        $u = $this->owner()->selectOne('SELECT mfa_locked_until FROM users WHERE id = ?', [$this->f['olive']->id]);
        $this->assertEqualsWithDelta(60 * 60, strtotime($u->mfa_locked_until) - time(), 30); // 15 min × 2²
        // The pending challenge token was dropped when the lock started.
        \Illuminate\Support\Facades\Auth::forgetGuards();
        $this->postJson('/api/v1/auth/mfa/login', ['code' => $this->totp($this->f['secret'])], ['Authorization' => "Bearer {$challenge}"])->assertStatus(401);
    }

    // --------------------------------------------------------- password reset
    public function test_password_reset_is_one_time_expiring_and_signs_out_everywhere(): void
    {
        $this->postJson('/api/v1/auth/forgot-password', ['email' => 'nobody@test.local'])->assertStatus(202);
        $same = $this->postJson('/api/v1/auth/forgot-password', ['email' => 'olive@test.local'])->assertStatus(202)->json('message');
        $this->assertSame($same, $this->postJson('/api/v1/auth/forgot-password', ['email' => 'nobody2@test.local'])->json('message'));
        $link = null;
        Mail::assertSent(SecurityNoticeMail::class, function ($m) use (&$link) { $link = $m->data['link'] ?? $link; return $m->kind === 'reset'; });
        Mail::assertSentCount(1);
        $token = substr($link, strpos($link, 'token=') + 6);
        $this->assertSame(64, strlen($token));
        $this->assertNull($this->owner()->selectOne('SELECT 1 AS x FROM password_reset_tokens WHERE token_hash = ?', [$token]), 'only the hash is stored');

        $session = $this->tokenFor($this->f['olive']);
        $this->postJson('/api/v1/auth/reset-password', ['token' => $token, 'password' => 'short', 'password_confirmation' => 'short'])->assertStatus(422);
        $this->postJson('/api/v1/auth/reset-password', ['token' => $token, 'password' => 'a-new-long-password', 'password_confirmation' => 'a-new-long-password'])->assertOk();
        $this->postJson('/api/v1/auth/reset-password', ['token' => $token, 'password' => 'another-long-password', 'password_confirmation' => 'another-long-password'])
            ->assertStatus(422);
        $this->getJson('/api/v1/auth/me', ['Authorization' => "Bearer {$session}"])->assertStatus(401);           // signed out everywhere
        Mail::assertSent(SecurityNoticeMail::class, fn ($m) => $m->kind === 'changed');
        // MFA is still required with the new password.
        $this->postJson('/api/v1/auth/login', ['email' => 'olive@test.local', 'password' => 'a-new-long-password'])->assertOk()->assertJsonPath('mfa_required', true);
        $this->assertNotEmpty($this->auditRows('user.password_reset'));
    }

    public function test_only_the_newest_link_works_links_expire_and_requests_are_capped(): void
    {
        foreach (range(1, 4) as $i) $this->postJson('/api/v1/auth/forgot-password', ['email' => 'olive@test.local'])->assertStatus(202);
        $links = [];
        Mail::assertSent(SecurityNoticeMail::class, function ($m) use (&$links) { if ($m->kind === 'reset') $links[] = $m->data['link']; return true; });
        $this->assertCount(3, $links, 'at most 3 reset emails per hour');
        $tok = fn ($l) => substr($l, strpos($l, 'token=') + 6);
        $body = fn ($t) => ['token' => $t, 'password' => 'a-new-long-password', 'password_confirmation' => 'a-new-long-password'];
        $this->postJson('/api/v1/auth/reset-password', $body($tok($links[0])))->assertStatus(422);
        $this->owner()->update("UPDATE password_reset_tokens SET expires_at = now() - interval '1 second' WHERE used_at IS NULL");
        $this->postJson('/api/v1/auth/reset-password', $body($tok($links[2])))->assertStatus(422);
    }

    // ------------------------------------------------------------- soft close
    public function test_closing_a_workspace_stops_activity_keeps_records_and_blocks_access(): void
    {
        [$site, $target] = $this->makeSite($this->f['ws'], null, 'shop.example');
        $ticket = $this->makeTicket($this->f['ws'], $site, 'investigating');
        $q = $this->api($this->f['olive'], $this->f['ws'], 'POST', "tickets/{$ticket}/quotes",
            ['monitor_target_id' => $target, 'action_code' => 'dns.record_fix', 'description' => 'Fix A'])->assertCreated()->json('id');
        $this->owner()->insert("INSERT INTO connectors(workspace_id, kind, label, secret_sealed, declared_capabilities, created_by)
                                VALUES (?, 'cloudflare', 'CF', 'v1:x', connector_declared('cloudflare'), ?)", [$this->f['ws'], $this->f['olive']->id]);

        $this->api($this->f['tina'], $this->f['ws'], 'POST', 'workspace/close', ['confirm_name' => 'Agency', 'reason' => 'Leaving'], mfaFresh: true)->assertForbidden();
        $this->api($this->f['olive'], $this->f['ws'], 'POST', 'workspace/close', ['confirm_name' => 'Agency', 'reason' => 'Leaving'])->assertStatus(403); // MFA
        $this->api($this->f['olive'], $this->f['ws'], 'POST', 'workspace/close', ['confirm_name' => 'agency', 'reason' => 'Leaving'], mfaFresh: true)->assertStatus(422);
        $this->api($this->f['olive'], $this->f['ws'], 'POST', 'workspace/close', ['confirm_name' => 'Agency', 'reason' => 'Leaving'], mfaFresh: true)->assertOk();

        // Every workspace route now answers 410 for members, 404 for strangers.
        $this->api($this->f['tina'], $this->f['ws'], 'GET', 'websites')->assertStatus(410)->assertJsonPath('code', 'workspace_closed');
        $this->api($this->f['olive'], $this->f['ws'], 'GET', 'clients')->assertStatus(410);
        $this->api($this->f['bob'], $this->f['ws'], 'GET', 'websites')->assertNotFound();
        // Background work stopped; credentials destroyed; quotes voided; records kept.
        $this->assertSame('suspended', $this->owner()->selectOne('SELECT state FROM monitor_targets WHERE id = ?', [$target])->state);
        $this->assertEmpty($this->worker()->select('SELECT * FROM worker_claim_due(10, 10, 60)'));
        $this->assertSame('revoked', $this->owner()->selectOne('SELECT secret_sealed FROM connectors')->secret_sealed);
        $this->assertNotNull($this->owner()->selectOne('SELECT voided_at FROM quotes WHERE id = ?', [$q])->voided_at);
        $this->assertSame(1, (int) $this->owner()->selectOne('SELECT count(*) AS n FROM quotes')->n);
        $this->assertTrue((bool) $this->owner()->selectOne('SELECT paused FROM repair_controls WHERE workspace_id = ?', [$this->f['ws']])->paused);
        try {
            $this->owner()->delete('DELETE FROM workspaces WHERE id = ?', [$this->f['ws']]);
            $this->fail('a workspace with financial records was deleted');
        } catch (QueryException) {
            $this->assertTrue(true);
        }
        // The switcher still lists it, marked closed.
        $this->assertNotNull(collect($this->api($this->f['olive'], null, 'GET', 'workspaces')->json('data'))->firstWhere('id', $this->f['ws'])['closed_at']);

        // Reopen: owner only, with MFA, within 30 days; monitoring restarts, credentials stay revoked.
        $this->api($this->f['tina'], null, 'POST', "workspaces/{$this->f['ws']}/reopen", [], mfaFresh: true)->assertNotFound();
        $this->api($this->f['olive'], null, 'POST', "workspaces/{$this->f['ws']}/reopen", [], mfaFresh: true)->assertOk();
        $this->api($this->f['tina'], $this->f['ws'], 'GET', 'websites')->assertOk();
        $this->assertSame('pending_validation', $this->owner()->selectOne('SELECT state FROM monitor_targets WHERE id = ?', [$target])->state);
        $this->assertSame('revoked', $this->owner()->selectOne('SELECT secret_sealed FROM connectors')->secret_sealed);

        $this->api($this->f['olive'], $this->f['ws'], 'POST', 'workspace/close', ['confirm_name' => 'Agency', 'reason' => 'Again'], mfaFresh: true)->assertOk();
        $this->owner()->update("UPDATE workspaces SET closed_at = now() - interval '31 days' WHERE id = ?", [$this->f['ws']]);
        $this->api($this->f['olive'], null, 'POST', "workspaces/{$this->f['ws']}/reopen", [], mfaFresh: true)->assertNotFound();
    }

    // -------------------------------------------------------- failure scenarios
    public function test_a_crashed_worker_lease_expires_and_the_work_is_picked_up_again(): void
    {
        // Connector worker claims, then dies without reporting.
        $id = $this->owner()->selectOne("INSERT INTO connectors(workspace_id, kind, label, secret_sealed, declared_capabilities, created_by)
                                         VALUES (?, 'cloudflare', 'CF', 'v1:x', connector_declared('cloudflare'), ?) RETURNING id", [$this->f['ws'], $this->f['olive']->id])->id;
        $this->assertCount(1, $this->worker()->select('SELECT * FROM worker_claim_connectors(10, 60)'));
        $this->assertCount(0, $this->worker()->select('SELECT * FROM worker_claim_connectors(10, 60)'), 'leased: no double processing');
        $this->owner()->update("UPDATE connectors SET lease_until = now() - interval '1 second' WHERE id = ?", [$id]);
        $this->assertCount(1, $this->worker()->select('SELECT * FROM worker_claim_connectors(10, 60)'), 'expired lease: picked up again');
        // Same for monitor targets.
        [, $target] = $this->makeSite($this->f['ws'], null, 'lease.example');
        $this->owner()->update("UPDATE monitor_targets SET next_check_at = now() - interval '1 minute' WHERE id = ?", [$target]);
        $this->assertCount(1, $this->worker()->select('SELECT * FROM worker_claim_due(10, 10, 60)'));
        $this->assertCount(0, $this->worker()->select('SELECT * FROM worker_claim_due(10, 10, 60)'));
        $this->owner()->update("UPDATE monitor_targets SET lease_until = now() - interval '1 second' WHERE id = ?", [$target]);
        $again = $this->worker()->select('SELECT * FROM worker_claim_due(10, 10, 60)');
        $this->assertCount(1, $again);
        $this->assertSame(2, (int) $again[0]->claims, 'the retry is counted, so the cycle is not double-counted');
    }

    public function test_a_payment_webhook_that_fails_midway_records_nothing_and_the_retry_succeeds(): void
    {
        $this->owner()->insert("INSERT INTO merchant_profiles(workspace_id, legal_name, razorpay_key_id, key_secret_enc, webhook_secret_enc, updated_by)
                                VALUES (?, 'M Ltd', 'rzp_test_AbCdEf123456', 'x', ?, ?)",
            [$this->f['ws'], \Illuminate\Support\Facades\Crypt::encryptString('hook-secret-0001'), $this->f['olive']->id]);
        $raw = json_encode(['event' => 'payment.captured', 'payload' => ['payment' => ['entity' => ['id' => 'pay_X0000000000001', 'order_id' => 'order_X00000000001',
            'amount' => 100, 'currency' => 'INR', 'status' => 'captured']]]]);
        $send = fn () => $this->call('POST', "/api/v1/webhooks/razorpay/{$this->f['ws']}", [], [], [], ['CONTENT_TYPE' => 'application/json',
            'HTTP_X_RAZORPAY_SIGNATURE' => hash_hmac('sha256', $raw, 'hook-secret-0001'), 'HTTP_X_RAZORPAY_EVENT_ID' => 'evt_Crash000001'], $raw);
        // Simulate the database failing inside processing.
        $this->owner()->unprepared("CREATE OR REPLACE FUNCTION payment_alert_boom() RETURNS trigger LANGUAGE plpgsql AS \$\$ BEGIN RAISE EXCEPTION 'disk full'; END \$\$;
            CREATE TRIGGER boom BEFORE INSERT ON payment_alerts FOR EACH ROW EXECUTE FUNCTION payment_alert_boom();");
        $this->assertSame(500, $send()->status());
        $this->assertSame(0, (int) $this->owner()->selectOne('SELECT count(*) AS n FROM payment_webhook_inbox')->n, 'nothing half-recorded: Razorpay will retry');
        $this->owner()->unprepared('DROP TRIGGER boom ON payment_alerts; DROP FUNCTION payment_alert_boom();');
        $send()->assertOk()->assertJsonPath('outcome', 'unknown_order');
        $this->assertSame(1, (int) $this->owner()->selectOne('SELECT count(*) AS n FROM payment_webhook_inbox')->n);
    }
